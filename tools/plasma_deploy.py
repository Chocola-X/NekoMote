#!/usr/bin/env python3
"""Complete Plasma wallpaper deployment tool for NekoMote.

Installs all components (KPackage + QML module + native library) to a prefix
rooted at XDG_DATA_HOME. Records every file with sha256 for verification and
clean uninstall. Rejects unsafe prefixes. Does not touch system paths or
desktop settings. Restarting plasmashell is explicit via --restart-shell.

Usage:
  plasma_deploy.py install   [--stage DIR] [--prefix DIR]
  plasma_deploy.py reinstall [--stage DIR] [--prefix DIR]
  plasma_deploy.py uninstall [--prefix DIR]
  plasma_deploy.py status    [--prefix DIR]
  plasma_deploy.py verify    [--prefix DIR]

Default stage:  build/plasma/adapters/plasma/stage
Default prefix: $XDG_DATA_HOME (or ~/.local/share if unset)
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path


REPO = Path(__file__).resolve().parent.parent
DEFAULT_STAGE = REPO / "build/plasma/adapters/plasma/stage"
RECORD_NAME = ".install-record.json"
PACKAGE_ID = "uk.nekopara.nekomote"
LEGACY_PACKAGE_ID = "org.nekomote.wallpaper"
ENVIRONMENT_NAME = "nekomote.conf"

UNSAFE_PREFIXES = {
    "/", "/usr", "/usr/local", "/etc", "/var", "/opt",
    "/bin", "/sbin", "/lib", "/lib64", "/boot", "/dev",
    "/proc", "/sys", "/root",
}

def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def default_prefix() -> Path:
    xdg = os.environ.get("XDG_DATA_HOME")
    if xdg:
        return Path(xdg)
    return Path.home() / ".local" / "share"


def validate_prefix(prefix: Path) -> None:
    if not prefix.is_absolute():
        sys.exit(f"FAIL: prefix must be absolute: {prefix}")
    resolved = str(prefix.resolve())
    if resolved in UNSAFE_PREFIXES:
        sys.exit(f"FAIL: unsafe prefix rejected: {prefix} (resolves to {resolved})")
    for unsafe in UNSAFE_PREFIXES:
        if resolved.startswith(unsafe + "/"):
            sys.exit(f"FAIL: prefix under unsafe path {unsafe}: {prefix}")
    if not prefix.parent.exists():
        sys.exit(f"FAIL: prefix parent does not exist: {prefix.parent}")


def stage_plasma_major(stage: Path) -> int:
    package = stage / "share/plasma/wallpapers" / PACKAGE_ID
    if (package / "metadata.desktop").is_file():
        return 5
    return 6


def stage_to_prefix_map(stage: Path) -> list[tuple[Path, Path]]:
    """Return list of (stage_path, relative_dest) for all installable files."""
    mapping = [
        (stage / "lib/libnekomote_plasma_qml.so",
         "nekomote/lib/libnekomote_plasma_qml.so"),
        (stage / "qml/NekoMote/Wallpaper/qmldir",
         "nekomote/qml/NekoMote/Wallpaper/qmldir"),
        (stage / "qml/NekoMote/Wallpaper/libnekomote_plasma_qmlplugin.so",
         "nekomote/qml/NekoMote/Wallpaper/libnekomote_plasma_qmlplugin.so"),
    ]
    if stage_plasma_major(stage) == 6:
        mapping.append((stage / "qml/NekoMote/Wallpaper/nekomote_plasma_qml.qmltypes",
                        "nekomote/qml/NekoMote/Wallpaper/nekomote_plasma_qml.qmltypes"))
    wallpaper_package = stage / "share/plasma/wallpapers" / PACKAGE_ID
    for p in sorted(wallpaper_package.rglob("*")):
        if p.is_file():
            rel = p.relative_to(stage / "share")
            mapping.append((p, str(rel)))
    for p in sorted((stage / "share/plasma/plasmoids/org.nekomote.validation").rglob("*")):
        if p.is_file():
            rel = p.relative_to(stage / "share")
            mapping.append((p, str(rel)))
    for p in sorted((stage / "licenses").rglob("*")):
        if p.is_file():
            mapping.append((p, str(Path("nekomote/licenses") / p.relative_to(stage / "licenses"))))
    return mapping


def environment_file() -> Path:
    config_home = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
    return config_home / "environment.d" / ENVIRONMENT_NAME


def environment_content(prefix: Path, major: int = 6) -> str:
    qml_path = prefix / "nekomote" / "qml"
    # environment.d is parsed by systemd, not by a shell. Keep this a plain,
    # single assignment instead of relying on shell-only ${VAR:-default} syntax.
    escaped = str(qml_path).replace("\\", "\\\\").replace('"', '\\"').replace("$", "$$")
    variable = "QML2_IMPORT_PATH" if major == 5 else "QML_IMPORT_PATH"
    return f'{variable}="{escaped}"\n'


def remove_recorded_environment(record: dict) -> None:
    info = record.get("session_environment")
    path = Path(info["path"]) if info else environment_file()
    if info and path.is_file():
        if sha256(path) == info.get("sha256"):
            path.unlink()
        else:
            print(f"uninstall: preserving modified session environment file: {path}")
    # Remove the exact file generated by previous script versions. Do not
    # remove a user-edited environment.d file.
    if not info and path.is_file():
        legacy = f'QML_IMPORT_PATH="{record.get("prefix", "")}/nekomote/qml:${{QML_IMPORT_PATH:-}}"\n'
        if path.read_text() == legacy:
            path.unlink()


def validate_stage(stage: Path) -> list[tuple[Path, str]]:
    if not stage.is_dir():
        sys.exit(f"FAIL: stage directory not found: {stage}\n"
                 f"  run: cmake --build build/plasma --target nekomote_plasma_stage")
    stage_manifest = stage / "manifest.json"
    if not stage_manifest.is_file():
        sys.exit(f"FAIL: stage manifest not found: {stage_manifest}")
    mapping = stage_to_prefix_map(stage)
    missing = [str(src) for src, _ in mapping if not src.is_file()]
    if missing:
        sys.exit(f"FAIL: missing stage files: {missing}")
    return mapping


def do_install(stage: Path, prefix: Path) -> int:
    validate_prefix(prefix)
    mapping = validate_stage(stage)
    record_path = prefix / "nekomote" / RECORD_NAME
    if record_path.is_file():
        sys.exit(f"already installed at {prefix}; use 'reinstall' to replace it")
    prefix.mkdir(parents=True, exist_ok=True)
    stage_manifest = stage / "manifest.json"
    env_path = environment_file()
    env_text = environment_content(prefix, stage_plasma_major(stage))
    env_path.parent.mkdir(parents=True, exist_ok=True)
    if env_path.exists():
        legacy = f'QML_IMPORT_PATH="{prefix}/nekomote/qml:${{QML_IMPORT_PATH:-}}"\n'
        if env_path.read_text() != legacy:
            sys.exit(f"refusing to overwrite existing environment file: {env_path}")
    record: dict = {
        "install_time": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "stage_dir": str(stage),
        "prefix": str(prefix),
        "stage_manifest_sha256": sha256(stage_manifest),
        "files": {},
        "session_environment": {"path": str(env_path)},
    }
    for src, rel in mapping:
        dst = prefix / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        record["files"][rel] = {"sha256": sha256(dst), "size": dst.stat().st_size}
    env_path.write_text(env_text)
    os.chmod(env_path, 0o644)
    record["session_environment"]["sha256"] = sha256(env_path)
    record_path.write_text(json.dumps(record, indent=2, sort_keys=True))
    print(f"install: {len(record['files'])} files to {prefix}")
    print(f"  KPackage:  {prefix}/plasma/wallpapers/{PACKAGE_ID}/")
    print(f"  Plasmoid:   {prefix}/plasma/plasmoids/org.nekomote.validation/")
    print(f"  Native lib: {prefix}/nekomote/lib/libnekomote_plasma_qml.so")
    print(f"  QML module: {prefix}/nekomote/qml/NekoMote/Wallpaper/")
    print(f"  Session env: {env_path}")
    print("  Activate: log out and back in, or restart plasmashell")
    print(f"  Record:     {record_path}")
    return 0


def do_uninstall(prefix: Path) -> int:
    validate_prefix(prefix)
    record_path = prefix / "nekomote" / RECORD_NAME
    if not record_path.is_file():
        print(f"uninstall: no install record at {record_path}")
        removed = 0
    else:
        record = json.loads(record_path.read_text())
        remove_recorded_environment(record)
        removed = 0
        for rel in record.get("files", {}):
            p = prefix / rel
            if p.is_file():
                p.unlink()
                removed += 1
        for rel in sorted(record.get("files", {}), reverse=True):
            d = (prefix / rel).parent
            while d != prefix and d.exists() and not any(d.iterdir()):
                d.rmdir()
                d = d.parent
        record_path.unlink()
    remove_legacy_package(prefix)
    print(f"uninstall: removed {removed} files from {prefix}")
    return 0


def remove_legacy_package(prefix: Path) -> None:
    """Remove the previous KPackage directory only when its metadata proves identity."""
    legacy_dir = prefix / "plasma" / "wallpapers" / LEGACY_PACKAGE_ID
    metadata_path = legacy_dir / "metadata.json"
    if not legacy_dir.exists():
        return
    if legacy_dir.is_symlink() or not legacy_dir.is_dir():
        print(f"uninstall: preserving non-directory legacy path: {legacy_dir}")
        return
    try:
        metadata = json.loads(metadata_path.read_text())
    except (OSError, json.JSONDecodeError):
        print(f"uninstall: preserving unverified legacy directory: {legacy_dir}")
        return
    plugin = metadata.get("KPlugin") if isinstance(metadata, dict) else None
    if not isinstance(plugin, dict) or plugin.get("Id") != LEGACY_PACKAGE_ID:
        print(f"uninstall: preserving directory with unexpected plugin ID: {legacy_dir}")
        return
    if metadata.get("KPackageStructure") != "Plasma/Wallpaper":
        print(f"uninstall: preserving directory with unexpected package type: {legacy_dir}")
        return
    shutil.rmtree(legacy_dir)
    print(f"uninstall: removed legacy package directory {legacy_dir}")


def do_reinstall(stage: Path, prefix: Path) -> int:
    validate_prefix(prefix)
    validate_stage(stage)
    result = do_uninstall(prefix)
    if result != 0:
        return result
    return do_install(stage, prefix)


def restart_plasmashell(prefix: Path, action: str, major: int = 6) -> int:
    quit_app = shutil.which(f"kquitapp{major}")
    start_app = (shutil.which("kstart5") if major == 5
                 else shutil.which("kstart") or shutil.which("kstart6"))
    if not quit_app or not start_app:
        print(f"restart: requires KDE {major} kquitapp/kstart tools", file=sys.stderr)
        return 1
    env = dict(os.environ)
    qml_path = str(prefix / "nekomote" / "qml")
    variable = "QML2_IMPORT_PATH" if major == 5 else "QML_IMPORT_PATH"
    if action != "uninstall":
        existing = env.get(variable, "")
        paths = [path for path in existing.split(":") if path and path != qml_path]
        env[variable] = ":".join([qml_path, *paths])
        update_env = shutil.which("dbus-update-activation-environment")
        if update_env:
            try:
                subprocess.run([update_env, "--systemd", variable],
                               check=True, env=env, timeout=10)
            except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as error:
                print(f"restart: failed to update session environment: {error}", file=sys.stderr)
                return 1
    else:
        env[variable] = ":".join(
            path for path in env.get(variable, "").split(":")
            if path and path != qml_path
        )
    try:
        running = subprocess.run(["pgrep", "-x", "plasmashell"],
                                 capture_output=True, check=False, timeout=5)
        if running.returncode == 0:
            subprocess.run([quit_app, "plasmashell"], check=True, env=env, timeout=15)
        subprocess.run([start_app, "plasmashell"], check=True, env=env, timeout=20)
    except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired) as error:
        print(f"restart: failed to restart plasmashell: {error}", file=sys.stderr)
        return 1
    print("restart: plasmashell restarted")
    return 0


def refresh_package_cache(major: int = 6) -> None:
    refresh = shutil.which(f"kbuildsycoca{major}")
    if not refresh:
        print(f"package cache: kbuildsycoca{major} unavailable; refresh it in the Plasma session")
        return
    try:
        result = subprocess.run([refresh, "--noincremental"], capture_output=True,
                                text=True, check=False, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as error:
        print(f"package cache: refresh failed: {error}", file=sys.stderr)
        return
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip()
        print(f"package cache: refresh failed ({result.returncode}): {detail}", file=sys.stderr)
    else:
        print("package cache: refreshed")


def do_status(prefix: Path) -> int:
    record_path = prefix / "nekomote" / RECORD_NAME
    if not record_path.is_file():
        print(f"status: not installed (no record at {record_path})")
        return 1
    record = json.loads(record_path.read_text())
    print(f"status: installed at {prefix}")
    print(f"  install_time: {record.get('install_time', '?')}")
    print(f"  stage_dir:    {record.get('stage_dir', '?')}")
    print(f"  files:        {len(record.get('files', {}))}")
    missing = []
    for rel in record.get("files", {}):
        if not (prefix / rel).is_file():
            missing.append(rel)
    if missing:
        print(f"  MISSING: {missing}")
        return 1
    print("  all files present")
    return 0


def do_verify(prefix: Path) -> int:
    record_path = prefix / "nekomote" / RECORD_NAME
    if not record_path.is_file():
        sys.exit(f"verify: no install record at {record_path}")
    record = json.loads(record_path.read_text())
    failures = []
    for rel, info in record.get("files", {}).items():
        p = prefix / rel
        if not p.is_file():
            failures.append(f"missing: {rel}")
            continue
        actual = sha256(p)
        if actual != info["sha256"]:
            failures.append(f"hash mismatch: {rel}")
    if failures:
        for f in failures:
            print(f"FAIL: {f}", file=sys.stderr)
        return 1
    print(f"verify: {len(record['files'])} files OK at {prefix}")
    return 0


def main() -> int:
    stage = Path(os.environ.get("NEKOMOTE_STAGE", DEFAULT_STAGE))
    prefix = Path(os.environ.get("NEKOMOTE_PREFIX", "")) if os.environ.get("NEKOMOTE_PREFIX") else default_prefix()
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("install", "reinstall", "uninstall", "status", "verify"))
    parser.add_argument("--stage", type=Path, default=stage)
    parser.add_argument(
        "--prefix", type=Path, default=prefix,
        help="user data install root (default: $XDG_DATA_HOME or ~/.local/share)",
    )
    parser.add_argument(
        "--restart-shell",
        action="store_true",
        help="restart plasmashell after install/reinstall/uninstall to activate the change now",
    )
    args = parser.parse_args()
    action = args.action
    stage = args.stage
    prefix = args.prefix
    if args.restart_shell and action in ("status", "verify"):
        parser.error("--restart-shell is only valid with install, reinstall, or uninstall")
    major = (stage_plasma_major(stage) if action in ("install", "reinstall")
             else 5 if (prefix / "plasma/wallpapers" / PACKAGE_ID / "metadata.desktop").is_file()
             else 6)
    if action == "install":
        result = do_install(stage, prefix)
    elif action == "uninstall":
        result = do_uninstall(prefix)
    elif action == "reinstall":
        result = do_reinstall(stage, prefix)
    elif action == "status":
        result = do_status(prefix)
    else:
        result = do_verify(prefix)
    if result == 0 and action in ("install", "reinstall", "uninstall"):
        refresh_package_cache(major)
    if result == 0 and args.restart_shell:
        return restart_plasmashell(prefix, action, major)
    return result


if __name__ == "__main__":
    sys.exit(main())
